// tools/promote-copilot-captures.mjs
//
// The corpus flywheel's PROMOTE half (dev-side). Reads copilot-captures.jsonl,
// reconciles 👍/👎 ratings by id, and templatizes the best LIVE captures into reusable
// lines — by swapping their LOGGED INPUT VALUES back into {slots}, never by parsing the
// prose. Merges them into server/ai/copilotPromotedData.js (the module the runtime
// imports), so a live beat's best lines become FREE on future installs. The runtime
// tries the promoted pool before paying for generation, sharing the same anti-repeat.
//
// Curated gate: promoted only when NET rating >= +1 (a thumbs-up, no net thumbs-down).
// Run offline, review copilotPromotedData.js, rebuild the exe.
//
//   node tools/promote-copilot-captures.mjs [capturesPath] [outPath]

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');
const CAPTURES = process.argv[2] || path.join(ROOT, 'copilot-captures.jsonl');
const OUT = process.argv[3] || path.join(ROOT, 'server', 'ai', 'copilotPromotedData.js');
const MIN_NET_RATING = 1;
// Beats that must NOT promote: freeform lines that reference arbitrary specifics the
// templatizer can't slot (they'd ship stale). whats-on-your-mind is premium/always-live
// by design; the haul beats weave per-run tonnages/commodities that won't generalize.
const EXCLUDE_BEATS = new Set(['whats-on-your-mind', 'dock-info', 'dock-complete', 'commodity-done', 'build-complete', 'news', 'tars-teach']);

function escapeRe(s) { return String(s).replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }

// Swap each scalar logged-input VALUE into a {key} slot. Longest values first (so a
// short value never clobbers part of a longer one); word-boundary + case-insensitive so
// "War" doesn't hit "Warning"; numbers matched both raw and comma-formatted. Inputs are
// what the app HANDED the beat — never guessed out of the prose.
function templatize(prose, inputs) {
  const cands = []; // [valueString, slotKey]
  for (const [k, v] of Object.entries(inputs || {})) {
    if (v == null || typeof v === 'boolean') continue;
    if (typeof v === 'number' && Number.isFinite(v)) {
      cands.push([String(v), k]);
      try { const loc = v.toLocaleString('en-US'); if (loc !== String(v)) cands.push([loc, k]); } catch { /* */ }
    } else if (typeof v === 'string' && v.trim().length >= 2) {
      cands.push([v.trim(), k]);
    }
  }
  cands.sort((a, b) => b[0].length - a[0].length);
  let out = prose;
  for (const [val, slot] of cands) {
    if (val.length < 2) continue;
    out = out.replace(new RegExp(`\\b${escapeRe(val)}\\b`, 'gi'), `{${slot}}`);
  }
  return out;
}

async function loadExisting() {
  if (!existsSync(OUT)) return {};
  try { const m = await import(pathToFileURL(OUT).href); return (m && m.default) || {}; }
  catch { return {}; }
}

async function run() {
  if (!existsSync(CAPTURES)) { console.error(`No capture log at ${CAPTURES}`); process.exit(1); }
  const byId = new Map();   // id -> line record
  const rating = new Map(); // id -> net rating
  for (const raw of readFileSync(CAPTURES, 'utf8').split('\n')) {
    if (!raw.trim()) continue;
    let r; try { r = JSON.parse(raw); } catch { continue; }
    if (r.kind === 'line' && r.id) byId.set(r.id, r);
    else if (r.kind === 'rating' && r.id) rating.set(r.id, (rating.get(r.id) || 0) + (Number(r.rating) || 0));
  }

  const out = await loadExisting();
  const keyOf = (p, b) => `${p}::${b}`;
  const seen = new Map(); // dedupe vs everything already promoted
  for (const [p, beats] of Object.entries(out)) for (const [b, arr] of Object.entries(beats || {})) {
    seen.set(keyOf(p, b), new Set(Array.isArray(arr) ? arr : []));
  }

  let promoted = 0; const summary = {};
  for (const [id, rec] of byId) {
    if (rec.source !== 'live') continue;            // canned/promoted are already in the pool
    if (EXCLUDE_BEATS.has(rec.beat)) continue;      // freeform/per-run beats don't generalize
    if ((rating.get(id) || 0) < MIN_NET_RATING) continue;
    if (!rec.prose || !rec.persona || !rec.beat) continue;
    const tmpl = templatize(String(rec.prose), rec.inputs).trim();
    if (!tmpl) continue;
    const k = keyOf(rec.persona, rec.beat);
    if (!seen.has(k)) seen.set(k, new Set());
    if (seen.get(k).has(tmpl)) continue;
    seen.get(k).add(tmpl);
    if (!out[rec.persona]) out[rec.persona] = {};
    if (!out[rec.persona][rec.beat]) out[rec.persona][rec.beat] = [];
    out[rec.persona][rec.beat].push(tmpl);
    promoted++; summary[k] = (summary[k] || 0) + 1;
  }

  const banner = '// AUTO-GENERATED by tools/promote-copilot-captures.mjs from rated LIVE captures.\n'
    + '// Promoted templates served free at runtime before live generation. Safe to delete to reset.\n'
    + '// Shape mirrors copilotCannedData.js: { [persona]: { [beatKey]: ["...{slot}..."] } }.\n';
  writeFileSync(OUT, `${banner}\nexport default ${JSON.stringify(out, null, 1)};\n`);
  console.log(`Read ${byId.size} captured line(s); promoted ${promoted} new -> ${path.relative(ROOT, OUT)}`);
  for (const [k, n] of Object.entries(summary)) console.log(`  +${n}  ${k}`);
  if (!promoted) console.log('  (nothing new — no LIVE lines met the +1 rating gate, or all already promoted)');
}

run().catch((e) => { console.error(e); process.exit(1); });
