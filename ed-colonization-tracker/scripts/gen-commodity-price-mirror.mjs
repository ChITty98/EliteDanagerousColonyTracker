// Generates server/journal/commodityPricesMirror.js from src/data/commodityPrices.ts.
//
// The server cannot import a .ts module, and the surface-mining overlay must price a tonne with
// the SAME number the page shows — including the prices the commander dictates (Ruby 74,000,
// Thortveitite 130,000, …). Run after editing the table:
//
//   node scripts/gen-commodity-price-mirror.mjs
//
// tests/commodity-price-mirror.test.mjs fails if the mirror drifts from the table.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const TABLE = path.join(ROOT, 'src', 'data', 'commodityPrices.ts');
export const MIRROR = path.join(ROOT, 'server', 'journal', 'commodityPricesMirror.js');

/** The ROWS block of the table: one `["id", "Name", "Category", avgSell, maxSell, avgBuy(, 1)]` per line. */
export function parseRows(text) {
  const start = text.indexOf('const ROWS');
  const end = text.indexOf('\n];', start);
  if (start < 0 || end < 0) throw new Error('commodityPrices.ts: ROWS block not found');
  const block = text.slice(start, end);
  const rows = [];
  let lines = 0;
  for (const line of block.split('\n')) {
    if (!/^\s*\["/.test(line)) continue;
    lines += 1;
    const m = line.match(/^\s*\["([^"]+)",\s*"([^"]+)",\s*"([^"]+)",\s*(\d+),\s*(\d+),\s*(\d+)(?:,\s*[01])?\],?\s*$/);
    if (!m) throw new Error(`commodityPrices.ts: unparsed row: ${line.trim()}`);
    rows.push({ id: m[1], name: m[2], category: m[3], avgSell: Number(m[4]) });
  }
  if (rows.length !== lines) throw new Error(`commodityPrices.ts: ${lines} rows, ${rows.length} parsed`);
  return rows;
}

export function render(rows) {
  const body = rows.map((r) => `  ${JSON.stringify(r.id)}: { name: ${JSON.stringify(r.name)}, avgSell: ${r.avgSell} },`).join('\n');
  return `// GENERATED by scripts/gen-commodity-price-mirror.mjs from src/data/commodityPrices.ts — do not edit.
// The server cannot import the .ts table; this mirror lets the surface-mining overlay price a
// tonne with the same number the page shows, including the prices the commander dictates.
// tests/commodity-price-mirror.test.mjs fails when this file drifts from the table.
export const COMMODITY_PRICE_MIRROR = {
${body}
};

// Diacritics stripped first ("Bastnäsite" → "bastnasite"), same as the page's flatten.
const flatten = (s) => String(s || '').normalize('NFD').replace(/[\\u0300-\\u036f]/g, '').toLowerCase().replace(/[^a-z0-9]/g, '');
const BY_KEY = new Map();
for (const [id, row] of Object.entries(COMMODITY_PRICE_MIRROR)) {
  BY_KEY.set(id, row);
  BY_KEY.set(flatten(row.name), row);
}

// Journal labels that do not flatten onto the table: "Low Temp. Diamonds" → lowtemperaturediamond
// (the only offender across every MiningRefined in the commander's journals; same rule as
// commodityKey in miningMissions.js).
const aliasKey = (k) => (k.startsWith('lowtemp') ? 'lowtemperaturediamond' : k);

function rowFor(name) {
  const k = aliasKey(flatten(name));
  return BY_KEY.get(k) || BY_KEY.get(k.replace(/s$/, '')) || BY_KEY.get(k + 's') || null;
}

// Live galactic averages from the game's own Market.json (MeanPrice), fed by marketMeans.js.
// They outrank the baked table: the table is the floor that works offline, the game is current.
let LIVE = new Map();
export function setLiveMeans(entries) {
  LIVE = new Map((entries || []).map(([k, v]) => [aliasKey(flatten(k)), Number(v) || 0]));
}

/** Galactic average sell per tonne: the game's live mean when known, else the table, else 0. */
export function galacticAvgSell(name) {
  const live = LIVE.get(aliasKey(flatten(name)));
  if (live > 0) return live;
  const row = rowFor(name);
  return row && row.avgSell > 0 ? row.avgSell : 0;
}

/** The table's spelling for a name typed by hand, or the name itself when unknown. */
export function canonicalCommodityName(name) {
  const row = rowFor(name);
  return row ? row.name : name;
}
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const rows = parseRows(fs.readFileSync(TABLE, 'utf8'));
  fs.writeFileSync(MIRROR, render(rows), 'utf8');
  console.log(`commodityPricesMirror.js: ${rows.length} commodities`);
}
