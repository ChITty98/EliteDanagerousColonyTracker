export interface CommodityPrice {
  id: string;
  name: string;
  category: string;
  avgSell: number;
  maxSell: number;
  avgBuy: number;
  rare: boolean;
}

export const COMMODITY_PRICES: CommodityPrice[] = ROWS.map(
  ([id, name, category, avgSell, maxSell, avgBuy, rare]) => ({
    id, name, category, avgSell, maxSell, avgBuy, rare: rare === 1,
  }),
);

/**
 * Journal ids are lowercase and unpunctuated, so "Micro-Weave Cooling Hoses" must be flattened.
 * Diacritics are stripped first ("Bastnäsite" → "bastnasite"), so an accented spelling from any
 * source still meets the journal's plain one instead of silently losing its price.
 */
export const flatten = (s: string): string =>
  s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^a-z0-9]/g, '');

const BY_KEY = new Map<string, CommodityPrice>();
for (const c of COMMODITY_PRICES) {
  BY_KEY.set(c.id, c);
  BY_KEY.set(flatten(c.name), c);
}

/**
 * Journal labels that do not flatten onto the table's names. Verified against every MiningRefined
 * in the commander's journals: the only offender is "Low Temp. Diamonds" (id lowtemperaturediamond).
 * Same rule the ring-mining module uses (commodityKey in miningMissions.js).
 */
const aliasKey = (k: string): string => (k.startsWith('lowtemp') ? 'lowtemperaturediamond' : k);

export function findCommodityPrice(name: string | null | undefined): CommodityPrice | undefined {
  if (!name) return undefined;
  const k = aliasKey(flatten(name));
  return BY_KEY.get(k) || BY_KEY.get(k.replace(/s$/, '')) || BY_KEY.get(k + 's');
}
